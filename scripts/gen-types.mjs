#!/usr/bin/env node
// Generate lib/db/types.gen.ts from the migrations (applied to an in-memory database).
// Usage: node scripts/gen-types.mjs [--check]   (--check exits 1 when the file is out of date)
import fs from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';
import { migrate } from '../lib/db/migrator.mjs';
import { migrationsDir } from '../lib/paths.mjs';

const OUT = path.join(process.cwd(), 'lib/db/types.gen.ts');

function tsType(col) {
  const t = String(col.type).toUpperCase();
  const base = t.includes('INT') ? 'number' : t.includes('REAL') ? 'number' : 'string';
  return col.notnull || col.pk ? base : `${base} | null`;
}

function pascal(name) {
  return name
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

export function generate() {
  const db = new Database(':memory:');
  migrate(db, migrationsDir());
  const tables = db
    .prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
    .all()
    .map((r) => r.name);
  let out = '// Generated by scripts/gen-types.mjs from migrations/. Do not edit.\n';
  for (const t of tables) {
    out += `\nexport interface ${pascal(t)}Row {\n`;
    for (const c of db.prepare(`PRAGMA table_info(${t})`).all()) out += `  ${c.name}: ${tsType(c)};\n`;
    out += '}\n';
  }
  db.close();
  return out;
}

const want = generate();
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== want) {
    console.error('lib/db/types.gen.ts is out of date: run npm run gen-types');
    process.exit(1);
  }
  console.log('lib/db/types.gen.ts is up to date');
} else {
  fs.writeFileSync(OUT, want);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
